//---------------------------------------------------------------------------
// Атрибуты в Private comment предмета коллекции Numista (задача 13a):
// "Код:значение" через ";". R — индекс редкости (0–100), S — обмен (Swap uCoin),
// C — свободный комментарий (последний, до конца строки). Неизвестные коды и
// куски без ":" пропускаются. Пример: "R:9;S:Am___cos /uid124372;C:text".
// Индекс можно записать и числом в начале (задача 20): "97" / "97;текст" — R = 97, текст — C.
//---------------------------------------------------------------------------
#ifndef u_NumistaCommentH
#define u_NumistaCommentH
//---------------------------------------------------------------------------
#include <System.hpp>
//---------------------------------------------------------------------------
struct TNumistaComment
{
	int    Rarity;	// -1 — нет (или неверное значение)
	String Swap;
	String Text;
	TNumistaComment() : Rarity(-1) {}

	static TNumistaComment Parse(const String &AComment);
	// Комментарий для выгрузки: "S:<swap>;C:<text>", пустые части не пишутся.
	static String Build(const String &ASwap, const String &AText);
	// Проверка разбора на наборе строк; "" — всё верно, иначе — первое расхождение.
	static String SelfTest();
};
//---------------------------------------------------------------------------
#endif
